// Teste funcional do formulário de orçamento (sem endpoint configurado).
import { chromium } from 'playwright-core';
const BASE = process.argv[2] ?? 'http://localhost:4322';
const b = await chromium.launch({ channel: 'msedge' });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const out = [];
await p.goto(`${BASE}/orcamento/?tipo=flexografia`, { waitUntil: 'load' });
out.push(['pré-seleção ?tipo=flexografia', await p.isChecked('#tipo-flexografia')]);
out.push(['medidas ocultas no início', await p.isHidden('#comp')]);
await p.click('button[type=submit]');
const errs = await p.locator('[data-error-summary] li').count();
out.push(['resumo de erros ao enviar vazio (itens)', errs]);
out.push(['foco no resumo', await p.evaluate(() => document.activeElement?.hasAttribute('data-error-summary'))]);
out.push(['aria-invalid no nome', await p.getAttribute('#nome', 'aria-invalid')]);
await p.fill('#nome', 'Teste QA');
await p.fill('#empresa', 'Empresa Teste');
await p.fill('#email', 'email-invalido');
await p.locator('#email').blur();
out.push(['mensagem de e-mail inválido', await p.textContent('#email-err')]);
await p.fill('#email', 'qa@empresa.com.br');
await p.type('#whatsapp', '62999998888');
out.push(['máscara de telefone', await p.inputValue('#whatsapp')]);
await p.fill('#cidade', 'Goiânia');
await p.selectOption('#uf', 'GO');
await p.check('#tem_medidas');
out.push(['medidas visíveis após "sim"', await p.isVisible('#comp')]);
await p.fill('#comp', '300'); await p.fill('#larg', '200'); await p.fill('#alt', '150');
await p.selectOption('#quantidade', { index: 2 });
await p.selectOption('#impressao', 'flexo');
out.push(['campo de arte visível com impressão', await p.isVisible('#arte')]);
await p.check('#lgpd');
await p.waitForTimeout(3100); // anti-spam: tempo mínimo de preenchimento
await p.click('button[type=submit]');
await p.waitForSelector('[data-result]:not([hidden])');
out.push(['estado do resultado', await p.getAttribute('[data-result]', 'data-state')]);
out.push(['título', await p.textContent('[data-result-title]')]);
const wa = await p.getAttribute('[data-fallback-wa]', 'href');
out.push(['link WhatsApp contém resumo', decodeURIComponent(wa).includes('Comprimento (mm): 300') && decodeURIComponent(wa).includes('Caixa em flexografia')]);
out.push(['link e-mail', (await p.getAttribute('[data-fallback-mail]', 'href')).startsWith('mailto:atendimento@goiaspel.com.br')]);
await p.screenshot({ path: 'qa/output/form-resultado-390.png', fullPage: false });
// honeypot
await p.goto(`${BASE}/contato/`, { waitUntil: 'load' });
await p.fill('#c-nome', 'Robô'); await p.type('#c-tel', '6232323232'); await p.check('#c-lgpd');
await p.evaluate(() => (document.querySelector('#c-site').value = 'spam'));
await p.waitForTimeout(3100);
await p.click('button[type=submit]');
await p.waitForSelector('[data-result]:not([hidden])');
out.push(['honeypot bloqueia', await p.getAttribute('[data-result]', 'data-state')]);
await b.close();
for (const [k, v] of out) console.log(`${k}: ${v}`);
